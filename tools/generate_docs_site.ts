function sidebarItem(page: DocsPage) {
  return {
    text: page.title,
    link: `/${page.target.replace(/\.md$/, "")}`,
  }
}

function rewriteMarkdownLinks(content: string, sourcePath: string): string {
  return content.replace(/\]\(([^)\s]+?\.md)(#[^)]+)?\)/g, (match, rawLink, anchor = "") => {
    if (/^https?:\/\//.test(rawLink)) return match
    const resolved = normalizePath(joinPath(dirname(sourcePath), rawLink))
    const target = targetBySource.get(resolved)
    if (!target) return match
    return `](/${target.replace(/\.md$/, "")}${anchor})`
  })
}

function normalizePath(path: string): string {
  const parts: string[] = []
  for (const part of path.split("/")) {
    if (!part || part === ".") continue
    if (part === "..") parts.pop()
    else parts.push(part)
  }
  return parts.join("/")
}

function joinPath(base: string, path: string): string {
  return normalizePath(`${base}/${path}`)
}

function dirname(path: string): string {
  const index = path.lastIndexOf("/")
  return index === -1 ? "." : path.slice(0, index)
}

if (import.meta.main) {
  const files = await generateDocsSiteFiles()
  Deno.exit(
    Deno.args.includes("--check") ? await checkGeneratedFiles(files) : await writeAndReport(files),
  )
}

async function writeAndReport(files: GeneratedDocsFile[]): Promise<number> {
  await writeGeneratedFiles(files)
  console.log(`Generated ${files.length} docs site files.`)
  return 0
}
