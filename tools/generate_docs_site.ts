const allPages = [...startPages, ...groups.flatMap((group) => group.pages)]
const targetBySource = new Map(allPages.map((page) => [normalizePath(page.source), page.target]))

export type GeneratedDocsFile = {
  path: string
  content: string
}

export async function generateDocsSiteFiles(): Promise<GeneratedDocsFile[]> {
  const files: GeneratedDocsFile[] = [
    { path: "docs-site/src/index.md", content: renderHomePage() },
    { path: "docs-site/src/quickstart.md", content: renderQuickstartPage() },
    { path: "docs-site/.vitepress/config.mts", content: renderVitePressConfig() },
    { path: "docs-site/README.md", content: renderDocsSiteReadme() },
  ]

  for (const page of allPages) {
    const source = await Deno.readTextFile(page.source)
    files.push({
      path: `docs-site/src/${page.target}`,
      content: `${generatedHeader}\n\n${rewriteMarkdownLinks(source, page.source)}\n`,
    })
  }

  return files
}

async function writeGeneratedFiles(files: GeneratedDocsFile[]) {
  for (const file of files) {
    await Deno.mkdir(dirname(file.path), { recursive: true })
    await Deno.writeTextFile(file.path, file.content)
  }
}

async function checkGeneratedFiles(files: GeneratedDocsFile[]): Promise<number> {
  const stale: string[] = []

  for (const file of files) {
    let current = ""
    try {
      current = await Deno.readTextFile(file.path)
    } catch {
      stale.push(file.path)
      continue
    }
    if (current !== file.content) stale.push(file.path)
  }

  if (stale.length > 0) {
    console.error([
      "Docs site is stale. Run:",
      "",
      "  deno task docs:site",
      "",
      "Stale files:",
      ...stale.map((file) => `- ${file}`),
    ].join("\n"))
    return 1
  }

  console.log("Docs site is current.")
  return 0
}

